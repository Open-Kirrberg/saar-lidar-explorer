# HYG star database v4.4 (CC BY-SA 4.0) -> viewer/src/starCatalogue.ts (stars brighter than V 5.0). KB-I93.
# The HYG database (David Nash / astronexus) compiles Hipparcos (2007 reduction), the Yale Bright Star Catalogue and
# Gliese; its README states "This work is licensed under a Creative Commons Attribution-ShareAlike 4.0 International
# License" (versions >= 4.0). The generated table is an adapted extract and stays under CC BY-SA 4.0 (header below);
# the viewer footer carries the attribution.
# Usage (source data stays in the git-ignored sources/ folder; the CSV is a git-lfs object, hence the media URL):
#   mkdir -p sources/hyg && curl -L -o sources/hyg/hyg_v44.csv.gz \
#     https://codeberg.org/astronexus/hyg/media/branch/main/data/hyg/CURRENT/hyg_v44.csv.gz
#   (sha256 00b349893b9a53106dd488d8371e8d2fa586043e500bb3cdb8bff3931682197d, 13,636,362 bytes, fetched 2026-11-02)
#   python3 -I scripts/stars/hyg-to-ts.py sources/hyg/hyg_v44.csv.gz viewer/src/starCatalogue.ts
# Columns used: ra (hours, J2000), dec (deg, J2000), pmra / pmdec (mas/yr; pmra is mu_alpha* = mu_alpha cos dec), mag
# (V), ci (B-V). Positions are carried by their proper motion to EPOCH (mid-July 1789), equinox J2000 kept: the viewer
# precesses the equinox to the date (ephemeris.ts). Stars without a colour index get B-V 0.6 (as the BSC5 generator).
import csv
import gzip
import math
import sys

EPOCH = 1789.54  # 15 Jul 1789 (Julian years)
MAG_LIMIT = 5.0

src, out = sys.argv[1], sys.argv[2]
opener = gzip.open if src.endswith('.gz') else open
rows = []
with opener(src, 'rt', encoding='utf-8', newline='') as f:
    for r in csv.DictReader(f):
        if r['id'] == '0' or r['proper'] == 'Sol':
            continue
        try:
            v = float(r['mag'])
            ra = float(r['ra']) * 15.0
            dec = float(r['dec'])
        except ValueError:
            continue
        if v >= MAG_LIMIT:
            continue
        try:
            bv = float(r['ci'])
        except ValueError:
            bv = 0.6
        try:
            pmra = float(r['pmra'] or 0)
            pmdec = float(r['pmdec'] or 0)
        except ValueError:
            pmra = pmdec = 0.0
        dt = EPOCH - 2000.0
        cosd = max(1e-6, math.cos(math.radians(dec)))
        ra = (ra + pmra * dt / 3.6e6 / cosd) % 360.0
        dec = dec + pmdec * dt / 3.6e6
        rows.append((ra, dec, v, bv))
rows.sort(key=lambda r: (r[2], r[0]))
flat = []
for ra, dec, v, bv in rows:
    flat += [f'{ra:.3f}', f'{dec:.3f}', f'{v:.2f}', f'{bv:.2f}']
with open(out, 'w') as f:
    f.write('/**\n')
    f.write(' * Stars brighter than V 5.0 from the HYG star database v4.4 (D. Nash, astronexus; Hipparcos 2007 reduction,\n')
    f.write(' * Yale Bright Star Catalogue 5th ed., Gliese; https://codeberg.org/astronexus/hyg) [D]. Licence: CC BY-SA 4.0\n')
    f.write(' * (https://creativecommons.org/licenses/by-sa/4.0/); this table is an adapted extract (V < 5, positions carried\n')
    f.write(f' * by their proper motion to epoch {EPOCH}) and is shared under the same licence. KB-I93.\n')
    f.write(' * Generated by scripts/stars/hyg-to-ts.py; do not edit. Per star: RA (deg), Dec (deg) for equinox J2000 at epoch\n')
    f.write(f' * {EPOCH}, V mag, B−V. Sorted by brightness.\n')
    f.write(' */\n')
    f.write(f'export const STAR_COUNT = {len(rows)};\n')
    f.write('/** Attribution line for the footer and photo exports (CC BY-SA 4.0 requires it). */\n')
    f.write("export const STAR_ATTRIBUTION = 'Sterne: HYG 4.4, CC BY-SA 4.0';\n")
    f.write('// prettier-ignore\nexport const STARS = new Float32Array([\n')
    for i in range(0, len(flat), 24):
        f.write('  ' + ', '.join(flat[i:i + 24]) + ',\n')
    f.write(']);\n')
print(len(rows))
