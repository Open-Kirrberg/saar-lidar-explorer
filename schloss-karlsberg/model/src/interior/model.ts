/**
 * Interior model of one building (pure, no three.js): everything buildInterior() draws, in
 * building [s, t] + absolute heights. Tests check it directly (stairs, door alignment,
 * furniture clearances) without rendering.
 *
 * Sources of truth: rooms / openings / stairs from the catalogue (v2), facade openings and the
 * storey stack from `layoutBuilding()` (via ctx.layout), norms from layout/grammar.ts.
 */
import { stToLocal } from '../layout/footprint.ts';
import type { BuildingLayout } from '../layout/building.ts';
import { mulberry32, hashString } from '../layout/geom.ts';
import { WALL_THICKNESS } from '../layout/grammar.ts';
import type { Poi } from '../context.ts';
import type { Building, Room, ST } from '../spec.ts';
import { evidenceLetters, silkColour } from './evidence.ts';
import { type IOpening, WALK_KINDS, collectOpenings } from './openings.ts';
import { type Grade, type Item, type RoomType, type RoomWall, classifyRoom, furnishRoom, gradeOf, roomWalls } from './programme.ts';
import { type Flight, type RectST, type StairPlan, flightRect, hallRect, planKey, planStair } from './stairPlan.ts';

export interface RoomModel {
  room: Room;
  type: RoomType;
  grade: Grade;
  floor_h: number;
  ceiling_h: number;
  wall_top: number;
  floorRects?: RectST[];
  ceilingRects?: RectST[];
  vault: boolean;
  walls: RoomWall[];
  items: Item[];
  evidence: string;
  colour: string;
  /** Room generated by the interiors (no catalogue programme). */
  generated: boolean;
}

export interface StairModel {
  plan: StairPlan;
  roomId: string;
  name_de: string;
  prunk: boolean;
  upperByRoom: boolean;
  evidence: string;
  tag: string;
}

export interface Stoop {
  roomId: string;
  name_de: string;
  landing: RectST;
  h: number;
  flight: Flight;
}

export interface LightSpec {
  roomId: string;
  position: [number, number, number]; // s, t, h
  colour: string;
  intensity: number;
  distance: number;
}

export interface InteriorModel {
  rooms: RoomModel[];
  openings: IOpening[];
  stairs: StairModel[];
  stoops: Stoop[];
  lights: LightSpec[];
  pois: Poi[];
  warnings: string[];
}

/** Highest door sill (above the room floor) that gets a few steps of its own. */
export const MAX_STOOP = 1.6;
const overlapArea = (a: RectST, b: RectST) => Math.max(0, Math.min(a.s1, b.s1) - Math.max(a.s0, b.s0)) * Math.max(0, Math.min(a.t1, b.t1) - Math.max(a.t0, b.t0));
const area = (r: RectST) => (r.s1 - r.s0) * (r.t1 - r.t0);
const clip = (r: RectST, b: RectST): RectST | null => {
  const c = { s0: Math.max(r.s0, b.s0), s1: Math.min(r.s1, b.s1), t0: Math.max(r.t0, b.t0), t1: Math.min(r.t1, b.t1) };
  return c.s1 - c.s0 > 0.05 && c.t1 - c.t0 > 0.05 ? c : null;
};

/** One hall for buildings with interior 'simple' and no room programme (tag I). */
export function generatedRooms(b: Building, layout: BuildingLayout): Room[] {
  const { frame, stack } = layout;
  const main = stack.floors.slice().sort((x, y) => y.height - x.height)[0];
  if (!main) return [];
  const w = WALL_THICKNESS[b.cls];
  let polygon: ST[];
  if (frame.shape === 'round') {
    const r = frame.radius ?? frame.width / 2;
    const k = (r - w) / r;
    polygon = frame.ringST.map(([s, t]) => [s * k, t * k] as ST);
  } else {
    polygon = [
      [-frame.length / 2 + w, -frame.width / 2 + w],
      [frame.length / 2 - w, -frame.width / 2 + w],
      [frame.length / 2 - w, frame.width / 2 - w],
      [-frame.length / 2 + w, frame.width / 2 - w],
    ];
  }
  const name = b.cls === 'RIDE' ? 'Reithalle (Bahn)' : b.cls === 'PAV' ? 'Rundsaal' : 'Halle';
  return [
    {
      id: `${b.id.replace('KB-', '')}.${main.index}.halle`,
      name_de: name,
      storey: main.index,
      polygon,
      finish: b.cls === 'RIDE' ? { floor: 'ground.gravel', walls: 'render.lime', ceiling: 'wall.limewash' } : { floor: 'floor.parquet', walls: 'wall.boiserie', ceiling: 'ceiling.stucco' },
      tag: `I generated single hall (no room programme in the catalogue); finish N`,
    },
  ];
}

function bboxOf(r: Room): RectST {
  return hallRect(r.polygon);
}

export function interiorModel(b: Building, layout: BuildingLayout, seed = 1789, groundAt?: (E: number, N: number) => number): InteriorModel {
  const warnings: string[] = [];
  const { stack, frame } = layout;
  const generated = !b.rooms?.length;
  const rooms = generated ? generatedRooms(b, layout) : b.rooms!;
  const dims = { L: frame.length, W: frame.width };
  const openings = collectOpenings(b, layout, groundAt);

  const base = rooms.map((room) => {
    const level = stack.levels[room.storey];
    const type = classifyRoom(room);
    return {
      room,
      type,
      grade: gradeOf(type, room),
      floor_h: room.floor_h ?? level?.floor_h ?? stack.base_h,
      ceiling_h: room.ceiling_h ?? level?.ceiling_h ?? stack.eaves_h,
      rect: bboxOf(room),
    };
  });

  // axial arch vestibule -> imperial stair hall (I): the catalogue only has side doors
  for (const v of base.filter((x) => x.type === 'vestibule')) {
    const st = (b.stairs ?? []).find((s) => s.kind === 'imperial');
    if (!st) continue;
    const hall = hallRect(st.polygon);
    const r = v.rect;
    const gapS = hall.s0 - r.s1 > -0.01 && hall.s0 - r.s1 < 0.7 ? (r.s1 + hall.s0) / 2 : r.s0 - hall.s1 > -0.01 && r.s0 - hall.s1 < 0.7 ? (r.s0 + hall.s1) / 2 : null;
    if (gapS === null) continue;
    const t0 = Math.max(r.t0, hall.t0);
    const t1 = Math.min(r.t1, hall.t1);
    const clearV = v.ceiling_h - v.floor_h;
    openings.push({
      id: `arch-${v.room.id}`,
      kind: 'passage',
      source: 'interior',
      storey: v.room.storey,
      centre: [gapS, (t0 + t1) / 2],
      dir: [0, 1],
      width: 3.0,
      bottom_h: v.floor_h,
      top_h: v.floor_h + Math.min(4.2, clearV - 0.4),
      head: 'round',
      rooms: [v.room.id, st.id.replace(/^stair-/, '')],
      facade: false,
      tag: 'I interiors: axial arch from the Vestibül into the Prunktreppenhaus (catalogue has side doors only)',
    });
  }

  // durchfahrt rooms sit at the level of their carriage opening (court level), not on the EG floor
  for (const x of base.filter((y) => y.type === 'durchfahrt')) {
    const walls = roomWalls(x.room, x.floor_h - 2, x.ceiling_h, openings, dims);
    const gate = walls.flatMap((w) => w.hits).find((h) => h.opening.kind === 'durchfahrt');
    if (gate && gate.opening.bottom_h < x.floor_h - 0.25) x.floor_h = gate.opening.bottom_h;
  }

  // ---- stairs ---------------------------------------------------------------------------------
  const stairs: StairModel[] = [];
  const floorRects = new Map<string, RectST[]>();
  const ceilingRects = new Map<string, RectST[]>();
  const wallTop = new Map<string, number>();
  const keepOut = new Map<string, [number, number, number, number][]>();
  const prevKey = new Map<string, string>();
  for (const st of (b.stairs ?? []).slice().sort((x, y) => x.storey_from - y.storey_from)) {
    const hall = hallRect(st.polygon);
    const hallRoom = base.find((x) => st.id === `stair-${x.room.id}`) ?? base.filter((x) => x.room.storey === st.storey_from).sort((p, q) => overlapArea(q.rect, hall) - overlapArea(p.rect, hall))[0];
    if (!hallRoom || overlapArea(hallRoom.rect, hall) < 0.5 * area(hall)) {
      warnings.push(`${st.id}: no room for the stair hall`);
      continue;
    }
    const upper = base.find((x) => x.room.storey === st.storey_to && overlapArea(x.rect, hall) > 0.5 * area(hall));
    const h0 = hallRoom.floor_h;
    const h1 = upper?.floor_h ?? stack.levels[st.storey_to]?.floor_h;
    if (h1 === undefined || h1 <= h0) continue;
    const doors = openings
      .filter((o) => WALK_KINDS.has(o.kind) && o.centre[0] > hall.s0 - 1.3 && o.centre[0] < hall.s1 + 1.3 && o.centre[1] > hall.t0 - 1.3 && o.centre[1] < hall.t1 + 1.3)
      .filter((o) => o.top_h > h0 && o.bottom_h < h1 + 0.5)
      .map((o) => ({ id: o.id, centre: o.centre, width: o.width, bottom_h: o.bottom_h }));
    const key = `${hall.s0.toFixed(1)}|${hall.t0.toFixed(1)}|${hall.s1.toFixed(1)}|${hall.t1.toFixed(1)}`;
    const plan = planStair({ stair: st, h0, h1, doors, prefer: prevKey.get(key) });
    prevKey.set(key, planKey(plan));
    if (plan.blocked.length) warnings.push(`${st.id}: ${plan.blocked.length} door(s) not served by the stair layout (${plan.blocked.join(', ')})`);
    const slabs = plan.landings.filter((l) => l.kind !== 'mid').map((l) => l.rect);
    if (upper) {
      floorRects.set(upper.room.id, [...(floorRects.get(upper.room.id) ?? []), ...slabs.map((r) => clip(r, upper.rect)).filter((r): r is RectST => !!r)]);
      ceilingRects.set(hallRoom.room.id, slabs.map((r) => clip(r, hallRoom.rect)).filter((r): r is RectST => !!r));
      wallTop.set(hallRoom.room.id, upper.floor_h);
    }
    keepOut.set(hallRoom.room.id, [...plan.flights.map(flightRect), ...plan.landings.map((l) => l.rect)].map((r) => [r.s0, r.s1, r.t0, r.t1]));
    stairs.push({
      plan,
      roomId: hallRoom.room.id,
      name_de: hallRoom.room.name_de,
      prunk: st.kind === 'imperial' || hallRoom.grade === 'state',
      upperByRoom: !!upper,
      evidence: evidenceLetters([st.tag, ...plan.notes]),
      tag: st.tag,
    });
  }

  // ---- rooms ----------------------------------------------------------------------------------
  const roomModels: RoomModel[] = base.map((x) => {
    const top = Math.max(x.ceiling_h, wallTop.get(x.room.id) ?? x.ceiling_h);
    const walls = roomWalls(x.room, x.floor_h, top, openings, dims);
    const isRect = x.room.polygon.length === 4;
    const vault = isRect && (['kitchen', 'bakery', 'scullery', 'cellar'] as RoomType[]).includes(x.type) && x.ceiling_h - x.floor_h >= 3;
    const colour = silkColour(x.room.finish?.walls);
    const items = furnishRoom({
      room: x.room,
      type: x.type,
      grade: x.grade,
      walls,
      floor_h: x.floor_h,
      ceiling_h: x.ceiling_h,
      colour,
      rnd: mulberry32((hashString(x.room.id) ^ seed) >>> 0),
      keepOut: keepOut.get(x.room.id),
    });
    return {
      room: x.room,
      type: x.type,
      grade: x.grade,
      floor_h: x.floor_h,
      ceiling_h: x.ceiling_h,
      wall_top: top,
      floorRects: floorRects.get(x.room.id),
      ceilingRects: ceilingRects.get(x.room.id),
      vault,
      walls,
      items,
      evidence: evidenceLetters([x.room.tag]),
      colour,
      generated,
    };
  });

  // ---- stoops: doors above the floor of a lowered room (Durchfahrt) -----------------------------
  const stoops: Stoop[] = [];
  for (const r of roomModels) {
    for (const w of r.walls) {
      for (const h of w.hits) {
        const o = h.opening;
        if (o.facade || !WALK_KINDS.has(o.kind)) continue;
        const dh = o.bottom_h - r.floor_h;
        // a few steps only: doors a whole storey up (galleries of a double-height stair hall) are
        // served by the stair's landings, or reported by the planner as blocked
        if (dh < 0.2 || dh > MAX_STOOP) continue;
        const uc = (h.hole.u0 + h.hole.u1) / 2;
        const depth = 1.0;
        const lw = o.width + 0.4;
        const towards = uc < w.len / 2 ? 1 : -1; // run the steps towards the middle of the wall
        const n = Math.ceil(dh / 0.16 - 1e-9);
        const riser = dh / n;
        const tread = 0.65 - 2 * riser;
        const p = (u: number, inset: number): ST => [w.p0[0] + w.d[0] * u + w.nIn[0] * inset, w.p0[1] + w.d[1] * u + w.nIn[1] * inset];
        const a = p(uc - lw / 2, 0);
        const c = p(uc + lw / 2, depth);
        const landing: RectST = { s0: Math.min(a[0], c[0]), s1: Math.max(a[0], c[0]), t0: Math.min(a[1], c[1]), t1: Math.max(a[1], c[1]) };
        const goingLen = (n - 1) * tread;
        const startU = uc + towards * (lw / 2 + goingLen);
        stoops.push({
          roomId: r.room.id,
          name_de: `${r.room.name_de} – Podesttreppe`,
          landing,
          h: o.bottom_h,
          flight: { id: `stoop-${o.id}`, start: p(startU, depth / 2), dir: [-w.d[0] * towards, -w.d[1] * towards], width: depth, risers: n, riser, tread, h0: r.floor_h },
        });
      }
    }
  }

  // ---- lights + POIs --------------------------------------------------------------------------
  const lights: LightSpec[] = [];
  const LIT: RoomType[] = ['festsaal', 'vestibule', 'stairhall', 'gallery', 'library', 'dining', 'kitchen', 'orangery'];
  for (const r of roomModels) {
    if (lights.length >= 4) break;
    if (!LIT.includes(r.type) || (r.type === 'stairhall' && r.grade !== 'state') || (r.type === 'dining' && lights.some((l) => roomModels.find((m) => m.room.id === l.roomId)?.type === 'dining'))) continue;
    const it = r.items.find((x) => x.kind === 'chandelier' || x.kind === 'lantern' || x.kind === 'hearth');
    const c = it?.pos ?? centreOf(r.room);
    const h = it?.kind === 'hearth' ? r.floor_h + 1.0 : r.ceiling_h - Math.min(1.6, (r.ceiling_h - r.floor_h) * 0.35);
    lights.push({ roomId: r.room.id, position: [c[0], c[1], h], colour: it?.kind === 'hearth' ? '#ff8a3c' : '#ffd9a0', intensity: r.type === 'gallery' || r.type === 'orangery' ? 40 : 25, distance: r.type === 'gallery' ? 40 : 18 });
  }
  const pois: Poi[] = roomModels
    .filter((r) => r.grade !== 'service' || r.type === 'kitchen' || r.type === 'stairhall')
    .map((r) => {
      const c = centreOf(r.room);
      const pos = stToLocal(frame, c[0], c[1], r.floor_h + 1.6);
      return { id: `${b.id}/${r.room.id}`, name_de: r.room.name_de, kind: 'room', position: pos, buildingId: b.id, roomId: r.room.id, text_de: r.room.function, tags: r.evidence };
    });

  return { rooms: roomModels, openings, stairs, stoops, lights, pois, warnings };
}

export function centreOf(r: Pick<Room, 'polygon'>): ST {
  const b = hallRect(r.polygon);
  return [(b.s0 + b.s1) / 2, (b.t0 + b.t1) / 2];
}
